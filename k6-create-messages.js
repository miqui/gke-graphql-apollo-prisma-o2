import http from 'k6/http';
import { check, sleep } from 'k6';
import { randomIntBetween } from 'https://jslib.k6.io/k6-utils/1.4.0/index.js';

export const options = {
  vus: __ENV.VUS ? parseInt(__ENV.VUS, 10) : 10,
  duration: __ENV.DURATION || '10s',
  thresholds: {
    http_req_failed: ['rate<0.01'],    // Error rate under 1%
    http_req_duration: ['p(95)<500'],  // 95% of requests below 500ms
  },
};

const BASE_URL = __ENV.BASE_URL || 'http://localhost/graphql';
const jsonHeaders = { 'Content-Type': 'application/json', 'Accept': 'application/json' };

const CREATE_AUTHOR_MUTATION = `
  mutation CreateAuthor($input: CreateAuthorInput!) {
    createAuthor(input: $input) { id }
  }
`;
const CREATE_MESSAGE_MUTATION = `
  mutation CreateMessage($input: CreateMessageInput!) {
    createMessage(input: $input) { id title content author { id } }
  }
`;

// Every message needs an author (see prisma/schema.prisma's required Message.author
// relation) - create one shared author up front rather than one per VU iteration.
export function setup() {
  const res = http.post(BASE_URL, JSON.stringify({
    query: CREATE_AUTHOR_MUTATION,
    variables: { input: { name: 'k6-create-messages', email: `k6-create-messages-${Date.now()}@example.com` } },
  }), { headers: jsonHeaders });

  if (res.status !== 200 || res.json().errors) {
    throw new Error(`setup: failed to create author, status ${res.status}, body ${res.body}`);
  }
  return { authorId: res.json().data.createAuthor.id };
}

export default function (data) {
  const res = http.post(BASE_URL, JSON.stringify({
    query: CREATE_MESSAGE_MUTATION,
    variables: {
      input: {
        title: `Load test message ${randomIntBetween(1, 1000000)}`,
        content: 'Generated by k6-create-messages.js',
        authorId: data.authorId,
      },
    },
  }), { headers: jsonHeaders, tags: { name: 'CreateMessage' } });

  check(res, {
    'status is 200': (r) => r.status === 200,
    'no errors': (r) => {
      try {
        return !r.json().errors;
      } catch (e) {
        return false;
      }
    },
    'response has id': (r) => {
      try {
        return !!r.json().data.createMessage.id;
      } catch (e) {
        return false;
      }
    },
  });

  // Simulate think time between 100ms and 300ms using k6-utils
  sleep(randomIntBetween(1, 3) * 0.1);
}
